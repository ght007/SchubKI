"""Knowledge-base editing: versioned files, checks before saving, automatic rebuild and publish.

What can be changed (from the Knowledge base page, Pro users):
  area "kb"  - the 8 curated files in data/kb (evidence cards, rules, glossary, method/fiber/band tables,
               source registry, S02 transcription), edited as text;
  area "raw" - source documents in data/raw (PDF, DOCX, TXT, MD), uploaded; a document is searched once it
               is registered in sources.json.

Every save is a new version stored in the table kb_files (Supabase first, local SQLite copy), with author,
time and comment, so it can be restored. A save is refused when the file does not parse or breaks a
guarantee the assistant relies on (every evidence quote must be on its page, every rule must name its
sources, every condition must be valid). After a save the knowledge base is rebuilt (ingest) and published
to Supabase (push_to_supabase.py), so the change is used from the next run on, on every machine. Machines
that start later pull the newest versions from Supabase first (sync_from_db).
"""
from __future__ import annotations

import base64
import difflib
import hashlib
import json
import logging
import re
import threading
import time
from pathlib import Path
from typing import Any

import yaml

from ..config import READABLE_SOURCE_TYPES, settings
from . import remote, store

log = logging.getLogger("afs.kbfiles")

KB_FILES = {
    "claims.jsonl": "Evidence cards: claim, source, page and the verbatim quote (one JSON object per line)",
    "rules.yaml": "Rules: conditions, findings, questions, method scores, path hints, each with sources",
    "glossary.yaml": "Glossary: terms, aliases (English/German), plain-language definitions, vague words",
    "sources.json": "Source registry: file, title and evidence level of every document",
    "methods.json": "Spectroscopy methods: ranges, strengths, limits, compatible fibers",
    "fibers.json": "Fiber types and their transmission ranges",
    "bands.json": "Analyte absorption bands for the spectral map",
    "s02_notes.md": "Transcription of the image-only S02 slides (searchable, quotable text)",
}
EVIDENCE_LEVELS = ("overview", "company slides", "proof_of_concept_in_vitro", "lab_demonstration", "business")
MAX_UPLOAD = 15 * 1024 * 1024
# Evaluation cases are never knowledge: registering them would put scenario text into the evidence
# (case-specific hard-coding, forbidden by the brief). Hidden from the list and refused on upload/register.
EXCLUDED_DOCS = re.compile(r"customer_scenarios|final_evaluation|scenario", re.I)

_SQLITE = """
CREATE TABLE IF NOT EXISTS kb_files (
    id INTEGER PRIMARY KEY AUTOINCREMENT, area TEXT NOT NULL, name TEXT NOT NULL, version INTEGER NOT NULL,
    sha TEXT NOT NULL, size INTEGER NOT NULL, content BLOB NOT NULL, author TEXT, comment TEXT, created TEXT,
    UNIQUE (area, name, version));
"""
_PG = """
create table if not exists public.kb_files (
    id bigint generated by default as identity primary key, area text not null, name text not null,
    version integer not null, sha text not null, size integer not null, content bytea not null,
    author text, comment text, created text, unique (area, name, version));
alter table public.kb_files enable row level security;
"""
_pg_ready = False


class KBError(Exception):
    def __init__(self, message: str, problems: list[str] | None = None, status: int = 400):
        super().__init__(message)
        self.problems = problems or []
        self.status = status


# ------------------------------------------------------------------ storage
_local_ready = False


def _local():
    """The shared SQLite connection; the table is created once, under the store lock (a rebuild may be
    writing on the same connection in another thread)."""
    global _local_ready
    if not _local_ready:
        with store.tx() as c:
            c.execute(_SQLITE.strip().rstrip(";"))
        _local_ready = True
    return store.con()


def _remote(fn):
    global _pg_ready
    if not remote.enabled():
        return None

    def go(c):
        global _pg_ready
        if not _pg_ready:
            c.execute(_PG)
            _pg_ready = True
        return fn(c)
    return remote._run(go)  # noqa: SLF001  (shared connection, lock and offline handling)


def _path(area: str, name: str) -> Path:
    if area == "kb":
        if name not in KB_FILES:
            raise KBError(f"'{name}' is not an editable knowledge-base file", status=404)
        return settings.kb_dir / name
    if area == "raw":
        clean = Path(name).name
        if EXCLUDED_DOCS.search(clean):
            raise KBError(f"'{clean}' looks like evaluation cases; cases are never part of the knowledge base")
        if clean != name or not clean.lower().endswith(READABLE_SOURCE_TYPES):
            raise KBError(f"'{name}' is not an allowed document name ({', '.join(READABLE_SOURCE_TYPES)})")
        return settings.raw_dir / clean
    raise KBError(f"Unknown area '{area}'", status=404)


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _latest(area: str, name: str) -> dict | None:
    rows = _remote(lambda c: c.execute("select version, sha, author, comment, created from public.kb_files "
                                       "where area = %s and name = %s order by version desc limit 1",
                                       (area, name)).fetchall())
    if rows:
        v, sha, author, comment, created = rows[0]
        return {"version": v, "sha": sha, "author": author, "comment": comment, "created": created}
    r = _local().execute("SELECT version, sha, author, comment, created FROM kb_files WHERE area=? AND name=? "
                         "ORDER BY version DESC LIMIT 1", (area, name)).fetchone()
    return dict(r) if r else None


def _store_version(area: str, name: str, data: bytes, author: str, comment: str) -> int:
    latest = _latest(area, name)
    version = (latest["version"] if latest else 0) + 1
    if latest is None and _path(area, name).exists():
        # first edit of a file: keep the original as version 1, so it can always be restored
        original = _path(area, name).read_bytes()
        _write_row(area, name, 1, original, "original", "as shipped")
        version = 2
    _write_row(area, name, version, data, author, comment)
    return version


def _write_row(area: str, name: str, version: int, data: bytes, author: str, comment: str) -> None:
    row = (area, name, version, _sha(data), len(data), data, author, comment, time.strftime("%Y-%m-%dT%H:%M:%S"))
    _local()
    with store.tx() as c:
        c.execute("INSERT OR REPLACE INTO kb_files(area, name, version, sha, size, content, author, comment, created) "
                  "VALUES (?,?,?,?,?,?,?,?,?)", row)
    _remote(lambda c: c.execute("insert into public.kb_files (area, name, version, sha, size, content, author, comment, "
                                "created) values (%s,%s,%s,%s,%s,%s,%s,%s,%s) on conflict (area, name, version) do nothing",
                                row))


def _write_file(area: str, name: str, data: bytes) -> None:
    path = _path(area, name)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_bytes(data)
    tmp.replace(path)          # atomic: a run never reads a half-written file


# ------------------------------------------------------------------ listing and reading
def list_files() -> dict:
    registered = {s["file"]: s for s in _registry().get("sources", [])}
    kb = []
    for name, about in KB_FILES.items():
        p = settings.kb_dir / name
        meta = _latest("kb", name) or {}
        kb.append({"area": "kb", "name": name, "about": about, "size": p.stat().st_size if p.exists() else 0,
                   "version": meta.get("version", 1), "author": meta.get("author", "original"),
                   "updated": meta.get("created", "")})
    raw = []
    for p in sorted(settings.raw_dir.glob("*")):
        if p.is_file() and p.suffix.lower() in READABLE_SOURCE_TYPES and not EXCLUDED_DOCS.search(p.name):
            meta = _latest("raw", p.name) or {}
            src = registered.get(p.name)
            raw.append({"area": "raw", "name": p.name, "size": p.stat().st_size, "registered": bool(src),
                        "source_id": src["id"] if src else None, "title": src.get("title") if src else None,
                        "version": meta.get("version", 1), "updated": meta.get("created", "")})
    return {"kb": kb, "raw": raw, "evidence_levels": list(EVIDENCE_LEVELS), "rebuild": status()}


def read(area: str, name: str) -> dict:
    p = _path(area, name)
    if not p.exists():
        raise KBError(f"{name} not found", status=404)
    data = p.read_bytes()
    if area == "kb":
        return {"area": area, "name": name, "text": data.decode("utf-8"), "sha": _sha(data)}
    return {"area": area, "name": name, "size": len(data), "sha": _sha(data)}


def history(area: str, name: str) -> list[dict]:
    _path(area, name)
    rows = _remote(lambda c: c.execute("select version, sha, size, author, comment, created from public.kb_files "
                                       "where area = %s and name = %s order by version desc", (area, name)).fetchall())
    if rows is None:
        rows = [tuple(r) for r in _local().execute("SELECT version, sha, size, author, comment, created FROM kb_files "
                                                   "WHERE area=? AND name=? ORDER BY version DESC", (area, name))]
    return [dict(zip(("version", "sha", "size", "author", "comment", "created"), r)) for r in rows]


def _version_content(area: str, name: str, version: int) -> bytes:
    r = _local().execute("SELECT content FROM kb_files WHERE area=? AND name=? AND version=?",
                         (area, name, version)).fetchone()
    if r:
        return bytes(r[0])
    rows = _remote(lambda c: c.execute("select content from public.kb_files where area = %s and name = %s "
                                       "and version = %s", (area, name, version)).fetchall())
    if rows:
        return bytes(rows[0][0])
    raise KBError(f"{name} version {version} not found", status=404)


# ------------------------------------------------------------------ checks
def _registry(text: str | None = None) -> dict:
    try:
        return json.loads(text if text is not None else (settings.kb_dir / "sources.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"sources": []}


def check(name: str, text: str) -> tuple[list[str], list[str]]:
    """(problems that block the save, warnings). Nothing is written."""
    problems: list[str] = []
    warnings: list[str] = []
    if name not in KB_FILES:
        return [f"'{name}' is not an editable knowledge-base file"], []
    try:
        if name.endswith(".json"):
            data = json.loads(text)
        elif name.endswith(".yaml"):
            data = yaml.safe_load(text)
        elif name.endswith(".jsonl"):
            data = []
            for i, line in enumerate(text.splitlines(), 1):
                if line.strip():
                    try:
                        data.append(json.loads(line))
                    except ValueError as exc:
                        problems.append(f"line {i}: not valid JSON ({exc.msg})")
        else:
            data = text
    except (ValueError, yaml.YAMLError) as exc:
        return [f"The file does not parse: {exc}"], []
    if problems:
        return problems, warnings
    known_sources = {s["id"] for s in _registry().get("sources", [])}

    if name == "claims.jsonl":
        from .pages import clear_caches, quote_on_page
        clear_caches()
        seen = set()
        for i, c in enumerate(data, 1):
            miss = [k for k in ("id", "claim", "source", "page", "quote") if not c.get(k)]
            if miss:
                problems.append(f"line {i}: missing {', '.join(miss)}")
                continue
            if c["id"] in seen:
                problems.append(f"line {i}: duplicate id {c['id']}")
            seen.add(c["id"])
            if c["source"] not in known_sources:
                problems.append(f"line {i} ({c['id']}): unknown source {c['source']} (register it in sources.json)")
            elif not quote_on_page(c["quote"], c["source"], int(c["page"])):
                problems.append(f"line {i} ({c['id']}): the quote is not on {c['source']} p.{c['page']}")
    elif name == "rules.yaml":
        rules = (data or {}).get("rules") if isinstance(data, dict) else None
        if not isinstance(rules, list):
            return ["The file needs a top-level 'rules:' list"], []
        seen = set()
        for i, r in enumerate(rules, 1):
            rid = (r or {}).get("id", f"#{i}")
            for k in ("id", "title", "when", "sources"):
                if not (r or {}).get(k):
                    problems.append(f"rule {rid}: missing '{k}'")
            if rid in seen:
                problems.append(f"rule {rid}: duplicate id")
            seen.add(rid)
            for s in (r or {}).get("sources") or []:
                if s.get("source") not in known_sources:
                    problems.append(f"rule {rid}: unknown source {s.get('source')}")
            if (r or {}).get("when"):
                problems += [f"rule {rid}: {p}" for p in _condition_problems(r["when"])]
            sev = ((r or {}).get("flag") or {}).get("severity")
            if sev and sev not in ("block", "warn", "info"):
                problems.append(f"rule {rid}: flag severity must be block, warn or info")
    elif name == "glossary.yaml":
        terms = (data or {}).get("terms") if isinstance(data, dict) else None
        if not isinstance(terms, list):
            return ["The file needs a top-level 'terms:' list"], []
        for i, t in enumerate(terms, 1):
            if not (t or {}).get("term") or not (t or {}).get("category"):
                problems.append(f"term #{i}: needs 'term' and 'category'")
    elif name == "sources.json":
        sources = (data or {}).get("sources") if isinstance(data, dict) else None
        if not isinstance(sources, list):
            return ["The file needs a 'sources' list"], []
        seen = set()
        for s in sources:
            sid = s.get("id", "?")
            for k in ("id", "file", "title", "evidence_level"):
                if not s.get(k):
                    problems.append(f"{sid}: missing '{k}'")
            if sid in seen:
                problems.append(f"{sid}: duplicate id")
            seen.add(sid)
            if s.get("file") and EXCLUDED_DOCS.search(s["file"]):
                problems.append(f"{sid}: evaluation cases cannot be a knowledge source")
            elif s.get("file") and not (settings.raw_dir / s["file"]).exists():
                problems.append(f"{sid}: file {s['file']} is not in the documents (upload it first)")
            if s.get("evidence_level") and s["evidence_level"] not in EVIDENCE_LEVELS:
                warnings.append(f"{sid}: evidence level '{s['evidence_level']}' is not one of {', '.join(EVIDENCE_LEVELS)}")
        removed = known_sources - seen
        if removed:
            used = _sources_in_use()
            for sid in sorted(removed & used):
                problems.append(f"{sid} is still cited by evidence cards or rules; remove those first")
    elif name in ("methods.json", "fibers.json", "bands.json"):
        current = json.loads((settings.kb_dir / name).read_text(encoding="utf-8"))
        if type(data) is not type(current):
            problems.append(f"Top level must stay a {type(current).__name__}")
        elif isinstance(current, dict) and set(current) - set(data):
            problems.append(f"Missing top-level keys: {', '.join(sorted(set(current) - set(data)))}")
    elif name == "s02_notes.md":
        pages = len(re.findall(r"^## S02 p\.\d+", text, re.M))
        before = len(re.findall(r"^## S02 p\.\d+", (settings.kb_dir / name).read_text(encoding="utf-8"), re.M))
        if pages == 0:
            problems.append("No '## S02 p.N' page headings found")
        elif pages < before:
            warnings.append(f"{before - pages} S02 page section(s) removed; evidence cards on them may fail")
    return problems, warnings


CONDITION_OPS = ("eq", "in", "not_in", "contains", "text_any", "min_items", "known")


def _condition_fields() -> set[str]:
    from ..schemas import Requirements
    return set(Requirements.model_fields) | {"premise_kinds", "text"}


def _condition_problems(cond: Any, where: str = "when") -> list[str]:
    """Static check of the rule condition language (engine/rules.py _test), every branch, not only the reached ones."""
    if not isinstance(cond, dict):
        return [f"{where}: a condition must be a mapping"]
    for group in ("all", "any"):
        if group in cond:
            items = cond[group]
            if not isinstance(items, list) or not items:
                return [f"{where}.{group}: needs a non-empty list"]
            out = []
            for i, c in enumerate(items):
                out += _condition_problems(c, f"{where}.{group}[{i}]")
            return out
    if "field" not in cond:
        return [f"{where}: needs 'field' (or 'all' / 'any')"]
    out = []
    if cond["field"] not in _condition_fields():
        out.append(f"{where}: unknown field '{cond['field']}'")
    ops = [k for k in cond if k != "field"]
    if len(ops) != 1 or ops[0] not in CONDITION_OPS:
        out.append(f"{where}: use exactly one of {', '.join(CONDITION_OPS)} (found {', '.join(ops) or 'none'})")
    elif ops[0] in ("in", "not_in", "text_any") and not isinstance(cond[ops[0]], list):
        out.append(f"{where}: '{ops[0]}' needs a list")
    return out


def _sources_in_use() -> set[str]:
    used = set()
    for line in (settings.kb_dir / "claims.jsonl").read_text(encoding="utf-8").splitlines():
        if line.strip():
            used.add(json.loads(line).get("source"))
    for r in yaml.safe_load((settings.kb_dir / "rules.yaml").read_text(encoding="utf-8")).get("rules", []):
        used |= {s.get("source") for s in r.get("sources", [])}
    return used


def preview(name: str, text: str) -> dict:
    """Checks + a unified diff against the current file, without saving."""
    old = _path("kb", name).read_text(encoding="utf-8")
    problems, warnings = check(name, text)
    diff = list(difflib.unified_diff(old.splitlines(), text.splitlines(), "current", "new", lineterm="", n=2))
    added = sum(1 for d in diff if d.startswith("+") and not d.startswith("+++"))
    removed = sum(1 for d in diff if d.startswith("-") and not d.startswith("---"))
    return {"ok": not problems, "problems": problems, "warnings": warnings, "diff": diff[:600],
            "diff_truncated": len(diff) > 600, "added": added, "removed": removed, "changed": old != text}


# ------------------------------------------------------------------ saving
def save_kb(name: str, text: str, author: str, comment: str = "", base_sha: str | None = None) -> dict:
    _path("kb", name)
    current = (settings.kb_dir / name).read_bytes()
    if base_sha and base_sha != _sha(current):
        raise KBError(f"{name} was changed by someone else since you opened it. Reload it and apply your edit again.",
                      status=409)
    if text.encode("utf-8") == current:
        raise KBError("No changes to save")
    problems, warnings = check(name, text)
    if problems:
        raise KBError(f"{name} was not saved: {len(problems)} problem(s)", problems)
    data = text.encode("utf-8")
    version = _store_version("kb", name, data, author, comment)
    _write_file("kb", name, data)
    log.info("KB file %s saved as version %s by %s", name, version, author)
    start_rebuild(f"{name} v{version}")
    return {"name": name, "version": version, "warnings": warnings, "rebuild": status()}


def upload_raw(filename: str, content_b64: str, author: str, comment: str = "") -> dict:
    name = Path(filename).name.replace(" ", "_")
    _path("raw", name)
    try:
        data = base64.b64decode(content_b64, validate=True)
    except ValueError as exc:
        raise KBError("The upload is not valid base64") from exc
    if not data:
        raise KBError("The file is empty")
    if len(data) > MAX_UPLOAD:
        raise KBError(f"The file is larger than {MAX_UPLOAD // (1024 * 1024)} MB")
    pages = _readable_pages(name, data)
    version = _store_version("raw", name, data, author, comment or "upload")
    _write_file("raw", name, data)
    src = next((s for s in _registry().get("sources", []) if s.get("file") == name), None)
    if src:                                  # replacing a registered document: rebuild now
        start_rebuild(f"{name} v{version}")
    return {"name": name, "version": version, "pages": pages, "registered_as": src["id"] if src else None,
            "next_id": _next_source_id(), "rebuild": status()}


def _readable_pages(name: str, data: bytes) -> int:
    """Refuse files that cannot be read as text pages (scanned or broken documents)."""
    suffix = Path(name).suffix.lower()
    try:
        if suffix == ".pdf":
            import pymupdf
            with pymupdf.open(stream=data, filetype="pdf") as doc:
                text = sum(len(p.get_text().strip()) for p in doc)
                if text < 50:
                    raise KBError("The PDF has no extractable text (scanned?). Add a text transcription instead.")
                return len(doc)
        if suffix == ".docx":
            import io
            import docx
            words = sum(len(p.text.split()) for p in docx.Document(io.BytesIO(data)).paragraphs)
            from .pages import DOCX_PAGE_WORDS
            return max(1, -(-words // DOCX_PAGE_WORDS))
        data.decode("utf-8")
        return 1
    except KBError:
        raise
    except Exception as exc:  # noqa: BLE001
        raise KBError(f"The file cannot be read: {exc}") from exc


def _next_source_id() -> str:
    nums = [int(m.group(1)) for s in _registry().get("sources", []) if (m := re.match(r"S(\d+)$", s.get("id", "")))]
    return f"S{(max(nums) + 1 if nums else 1):02d}"


def register_source(entry: dict, author: str) -> dict:
    """Add an uploaded document to sources.json (through the normal checked save, so it is versioned)."""
    reg = _registry()
    entry = {k: v for k, v in entry.items() if v not in (None, "")}
    entry.setdefault("id", _next_source_id())
    if any(s["id"] == entry["id"] for s in reg["sources"]):
        raise KBError(f"{entry['id']} already exists")
    entry.setdefault("cite_as", f"{entry['id']} p.N")
    reg["sources"].append(entry)
    return save_kb("sources.json", json.dumps(reg, indent=2, ensure_ascii=False) + "\n", author,
                   f"register {entry['id']} ({entry.get('file')})")


def restore(area: str, name: str, version: int, author: str) -> dict:
    data = _version_content(area, name, version)
    if area == "kb":
        return save_kb(name, data.decode("utf-8"), author, f"restore version {version}")
    v = _store_version(area, name, data, author, f"restore version {version}")
    _write_file(area, name, data)
    start_rebuild(f"{name} restored to v{version}")
    return {"name": name, "version": v, "rebuild": status()}


# ------------------------------------------------------------------ rebuild + publish
_rebuild_lock = threading.Lock()
_status: dict[str, Any] = {"state": "idle", "message": "", "reason": "", "started": "", "finished": "",
                           "records": None, "queued": False}


def status() -> dict:
    return dict(_status)


def clear_caches() -> None:
    from ..engine import context, coverage, glossary, rules, verify
    from ..render import outline
    from .pages import clear_caches as clear_pages
    clear_pages()
    for fn in (rules.load_rules, glossary.entries, glossary._patterns, coverage.kb, verify._kb_number_text,  # noqa: SLF001
               verify.limited_scope, context.claims_by_page, outline._sources):  # noqa: SLF001
        fn.cache_clear()
    store.clear_vector_cache()


def start_rebuild(reason: str) -> None:
    """Rebuild in the background; a save during a rebuild queues one more rebuild."""
    if not _rebuild_lock.acquire(blocking=False):
        _status["queued"] = True
        return
    threading.Thread(target=_rebuild, args=(reason,), name="kb-rebuild", daemon=True).start()


def _rebuild(reason: str) -> None:
    from ..api.assess import _RUN_LOCK
    try:
        while True:
            _status.update(state="running", message="Rebuilding the knowledge base", reason=reason,
                           started=time.strftime("%Y-%m-%dT%H:%M:%S"), finished="", queued=False)
            for _ in range(2):            # wait for running assessments, block new ones while the index is rebuilt
                _RUN_LOCK.acquire()
            try:
                clear_caches()
                from . import ingest
                stats = ingest.run()
                clear_caches()
            except BaseException as exc:  # noqa: BLE001  (ingest raises SystemExit on bad data)
                _status.update(state="failed", message=f"Rebuild failed: {exc}", finished=time.strftime("%Y-%m-%dT%H:%M:%S"))
                log.error("KB rebuild failed: %s", exc)
                return
            finally:
                _RUN_LOCK.release()
                _RUN_LOCK.release()
            records = stats.get("records")
            message = f"Live: {records} records (local)"
            if remote.enabled():
                _status.update(state="publishing", records=records, message="Publishing to Supabase")
                try:
                    store.publish_kb_if_needed()
                    message = f"Live: {records} records, published to Supabase" if store.kb_online() else \
                        f"Live: {records} records locally; Supabase offline, published on the next sync"
                except Exception as exc:  # noqa: BLE001
                    log.warning("KB publish failed (kept locally, retried later): %s", exc)
                    message = f"Live: {records} records locally; publishing failed ({str(exc).splitlines()[0][:120]})"
            _status.update(state="done", records=records, message=message, finished=time.strftime("%Y-%m-%dT%H:%M:%S"))
            if not _status["queued"]:
                return
            reason = "queued changes"
    finally:
        _rebuild_lock.release()


# ------------------------------------------------------------------ startup: pull teammates' changes
def sync_from_db() -> list[str]:
    """Write the newest version of every file stored in Supabase to disk when it differs; rebuild if needed."""
    if not remote.enabled():
        return []
    rows = _remote(lambda c: c.execute(
        "select distinct on (area, name) area, name, version, sha from public.kb_files "
        "order by area, name, version desc").fetchall())
    changed = []
    for area, name, version, sha in rows or []:
        try:
            path = _path(area, name)
        except KBError:
            continue
        if path.exists() and _sha(path.read_bytes()) == sha:
            continue
        data = _remote(lambda c: c.execute("select content from public.kb_files where area = %s and name = %s "
                                           "and version = %s", (area, name, version)).fetchone())
        if data:
            _write_file(area, name, bytes(data[0]))
            changed.append(f"{name} v{version}")
    if changed:
        log.info("Pulled knowledge-base changes from Supabase: %s", ", ".join(changed))
        start_rebuild("pulled from Supabase: " + ", ".join(changed))
    return changed
