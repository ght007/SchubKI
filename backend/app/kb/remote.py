"""Hosted Postgres (Supabase) as the app's main database.

With SUPABASE_DB_URL set (and DB_BACKEND not "sqlite"), Supabase is the source of truth:

  knowledge base  keyword search (Postgres full text, OR of the query words, ts_rank_cd) and dense
                  search (pgvector cosine) run in Supabase; chunks and vectors are read from there.
                  The knowledge base is published with `python scripts/push_to_supabase.py` after an ingest.
  runs, cache,    written to Supabase first; a local copy is kept in SQLite so the app can fall back.
  feedback        Read from Supabase (the LLM cache is read locally first: same key, same reply).

Offline fallback: if Supabase cannot be reached, or its knowledge base is missing or was built with a
different embedding backend, everything runs on the local SQLite file and the header says so. The app
retries at most once a minute. Rows saved while offline are uploaded by push_to_supabase.py (it merges
runs, cache and feedback). Every function here returns None when Supabase is not usable; store.py then
uses SQLite.
"""
from __future__ import annotations

import logging
import os
import re
import threading
import time
from typing import Any, Callable
from urllib.parse import urlsplit

import numpy as np

log = logging.getLogger("afs.remote")

RETRY_AFTER_S = 60
CONNECT_TIMEOUT_S = 6

DDL = """
create table if not exists public.runs (
    id text primary key, created text not null, parent text, mode text, enquiry text, status text, json jsonb not null);
create index if not exists runs_created_idx on public.runs (created desc);
create table if not exists public.llm_cache (
    key text primary key, model text, response text not null, usage text, created double precision);
create table if not exists public.feedback (
    id bigint generated by default as identity primary key, run_id text, created text, target text, verdict text, comment text);
alter table public.runs enable row level security;
alter table public.llm_cache enable row level security;
alter table public.feedback enable row level security;
select setval(pg_get_serial_sequence('public.feedback', 'id'), coalesce((select max(id) from public.feedback), 0) + 1, false);
"""

_lock = threading.RLock()
_conn = None
_state: dict[str, Any] = {"status": "off", "error": "", "since": 0.0, "next_try": 0.0, "ready": False,
                          "kb": None, "kb_reason": "", "written": 0, "pending": 0}


# ------------------------------------------------------------------ configuration
def url() -> str:
    return os.getenv("SUPABASE_DB_URL", "").strip()


def enabled() -> bool:
    """Supabase is the main database unless DB_BACKEND=sqlite forces local-only."""
    return bool(url()) and os.getenv("DB_BACKEND", "supabase").strip().lower() != "sqlite"


def target() -> str:
    """Host and database for display; never the password."""
    p = urlsplit(effective_url())
    return f"{p.hostname}:{p.port or 5432}{p.path}" if p.hostname else ""


# ------------------------------------------------------------------ IPv4 pooler discovery
# The direct db.<ref>.supabase.co host is IPv6-only; many networks cannot reach it. Supabase's session
# pooler speaks IPv4 at aws-0/1-<region>.pooler.supabase.com with user "postgres.<ref>". The region is not
# in the URL, so every region is tried once (a wrong region answers "Tenant or user not found" at once).
# The address found is remembered in data/cache/supabase_pooler.json (git-ignored), keyed by a hash of
# SUPABASE_DB_URL, so the search runs only once per URL.
POOLER_REGIONS = ("eu-central-1", "eu-central-2", "eu-west-1", "eu-west-2", "eu-west-3", "eu-north-1",
                  "us-east-1", "us-east-2", "us-west-1", "us-west-2", "ca-central-1", "sa-east-1",
                  "ap-south-1", "ap-southeast-1", "ap-southeast-2", "ap-northeast-1", "ap-northeast-2")
_discovered: dict[str, str] = {}


def _pooler_file():
    from ..config import settings
    return settings.db_path.parent / "supabase_pooler.json"


def _url_key(u: str) -> str:
    import hashlib
    return hashlib.sha256(u.encode()).hexdigest()[:16]


def pooler_candidates(u: str) -> list[str]:
    p = urlsplit(u)
    host = p.hostname or ""
    if not (host.startswith("db.") and host.endswith(".supabase.co")):
        return []
    ref = host[3:-len(".supabase.co")]
    user = p.username or "postgres"
    if "." not in user:
        user = f"{user}.{ref}"
    pw = u.split("://", 1)[1].rsplit("@", 1)[0].split(":", 1)[1] if p.password is not None else ""
    path = p.path or "/postgres"
    query = f"?{p.query}" if p.query else ""
    return [f"postgresql://{user}:{pw}@{pre}-{region}.pooler.supabase.com:5432{path}{query}"
            for pre in ("aws-0", "aws-1") for region in POOLER_REGIONS]


def effective_url() -> str:
    """SUPABASE_DB_URL, or the IPv4 pooler address found for it earlier."""
    u = url()
    if not u:
        return ""
    k = _url_key(u)
    if k not in _discovered:
        try:
            import json
            saved = json.loads(_pooler_file().read_text(encoding="utf-8"))
            if saved.get("for") == k and saved.get("url"):
                _discovered[k] = saved["url"]
        except Exception:  # noqa: BLE001  (no file yet)
            pass
    return _discovered.get(k, u)


def discover_pooler() -> str | None:
    """Try the session pooler in every region. Returns the working URL (and remembers it) or None."""
    import json
    import psycopg
    u = url()
    for cand in pooler_candidates(u):
        try:
            with psycopg.connect(cand, prepare_threshold=None, connect_timeout=5) as c:
                c.execute("select 1")
        except Exception as exc:  # noqa: BLE001
            if "password authentication failed" in str(exc):
                _state["error"] = ("found the Supabase pooler but the password was rejected: check the password in "
                                   "SUPABASE_DB_URL (write '@' as %40)")
                return None
            continue                                    # wrong region / host does not exist
        _discovered[_url_key(u)] = cand
        try:
            _pooler_file().parent.mkdir(parents=True, exist_ok=True)
            _pooler_file().write_text(json.dumps({"for": _url_key(u), "url": cand}), encoding="utf-8")
        except OSError:
            pass
        p = urlsplit(cand)
        log.info("Supabase: direct host unreachable (IPv6); using the IPv4 session pooler %s", p.hostname)
        return cand
    return None


def _clean(v):
    return v.replace("\x00", "") if isinstance(v, str) else v   # Postgres text cannot hold NUL


# ------------------------------------------------------------------ connection
def _connect():
    """Open (or reuse) the connection. Returns None while offline; retries at most once a minute."""
    global _conn
    if not enabled():
        return None
    if _conn is not None and not _conn.closed:
        return _conn
    now = time.time()
    if now < _state["next_try"]:
        return None
    try:
        import psycopg
    except ImportError:
        _offline('psycopg missing: pip install "psycopg[binary]"', retry_s=3600)
        return None
    try:
        # autocommit: each statement is its own transaction; prepare_threshold=None for Supabase poolers
        try:
            _conn = psycopg.connect(effective_url(), autocommit=True, prepare_threshold=None,
                                    connect_timeout=CONNECT_TIMEOUT_S)
        except Exception as exc:  # noqa: BLE001
            unreachable = any(s in str(exc) for s in ("resolve", "getaddrinfo", "unreachable", "Name or service"))
            if not (unreachable and effective_url() == url() and pooler_candidates(url())):
                raise
            log.info("Supabase: direct host not reachable from this network; searching for the IPv4 pooler ...")
            found = discover_pooler()
            if not found:
                raise RuntimeError(_state["error"] if "password" in _state.get("error", "") else
                                   "direct host is IPv6-only and no IPv4 session pooler answered: copy the "
                                   "'Session pooler' URI from Supabase > Connect into SUPABASE_DB_URL") from exc
            _conn = psycopg.connect(found, autocommit=True, prepare_threshold=None, connect_timeout=CONNECT_TIMEOUT_S)
        _conn.execute("set search_path = public, extensions")   # pgvector's <=> lives in "extensions" on Supabase
        if not _state["ready"]:
            _conn.execute(DDL)
            _state["ready"] = True
        _state.update(status="online", error="", since=now)
        log.info("Supabase online: %s", target())
        return _conn
    except Exception as exc:  # noqa: BLE001  (network, DNS, auth: all mean "offline")
        _conn = None
        msg = str(exc).strip().splitlines()[0][:300] if str(exc).strip() else exc.__class__.__name__
        _offline(msg)
        return None


def _offline(msg: str, retry_s: float = RETRY_AFTER_S) -> None:
    _state.update(status="offline", error=msg, next_try=time.time() + retry_s)
    log.warning("Supabase offline, using local SQLite: %s", msg)


def _run(fn: Callable[[Any], Any]) -> Any:
    """Run fn(conn) under the lock. Returns None when offline or on error (the connection is dropped)."""
    global _conn
    with _lock:
        c = _connect()
        if c is None:
            return None
        try:
            return fn(c)
        except Exception as exc:  # noqa: BLE001
            _offline(str(exc).strip().splitlines()[0][:200] if str(exc).strip() else exc.__class__.__name__)
            try:
                c.close()
            finally:
                _conn = None
            return None


def online() -> bool:
    return _run(lambda c: c.execute("select 1").fetchone()) is not None


# ------------------------------------------------------------------ knowledge base
def kb_ready(local_embed_backend: str, local_ingested_at: str = "", local_hash: str = "") -> bool:
    """Use the hosted knowledge base only if it exists, matches the local embedding backend (query vectors
    are made locally; a 384-d bge query cannot search 1024-d hashing vectors) and comes from the same ingest
    as the local copy (chunk ids must match, so a fallback mid-run never mixes two different indexes)."""
    if not enabled():
        return False
    if _state["kb"] is not None and _state["status"] == "online":
        return _state["kb"]

    def check(c):
        missing = c.execute("select to_regclass('public.chunks') is null or to_regclass('public.vectors') is null "
                            "or to_regclass('public.meta') is null").fetchone()[0]
        if missing:
            return "missing"
        n = c.execute("select count(*) from public.chunks").fetchone()[0]
        nv = c.execute("select count(*) from public.vectors").fetchone()[0]
        meta = dict(c.execute("select key, value from public.meta "
                              "where key in ('embed_backend', 'ingested_at', 'kb_hash')").fetchall())
        return n, nv, meta.get("embed_backend", ""), meta.get("ingested_at", ""), meta.get("kb_hash", "")

    res = _run(check)
    if res is None:                      # offline
        return False
    if res == "missing":                 # online, but the knowledge base was never pushed
        _state.update(kb=False, kb_reason="no knowledge base online yet: run scripts/push_to_supabase.py")
        log.warning("Using the local knowledge base: %s", _state["kb_reason"])
        return False
    n, nv, backend, ingested, online_hash = res
    # same content fingerprint = same index, even if built at another time on another machine
    same_build = (online_hash == local_hash) if (online_hash and local_hash) else \
        not (local_ingested_at and ingested and ingested != local_ingested_at)
    if n == 0 or nv == 0:
        _state.update(kb=False, kb_reason="knowledge base online is empty: run scripts/push_to_supabase.py")
    elif backend and backend != local_embed_backend:
        _state.update(kb=False, kb_reason=f"online knowledge base uses '{backend}' embeddings, this machine "
                                          f"'{local_embed_backend}': re-ingest and push again")
    elif not same_build:
        _state.update(kb=False, kb_reason=f"online knowledge base differs from this machine's files ({ingested}, local "
                                          f"{local_ingested_at}): it is republished automatically, or run scripts/push_to_supabase.py")
    else:
        _state.update(kb=True, kb_reason="")
    if not _state["kb"]:
        log.warning("Using the local knowledge base: %s", _state["kb_reason"])
    return _state["kb"]


def kb_size() -> int | None:
    row = _run(lambda c: c.execute("select count(*) from public.chunks").fetchone())
    return None if row is None else int(row[0])


def get_meta(key: str) -> str | None:
    row = _run(lambda c: c.execute("select value from public.meta where key = %s", (key,)).fetchone())
    return None if row is None else (row[0] or "")


_COLS = ("id", "kind", "source", "page", "text", "quote", "scope", "claim_id")
_SEL = "select id, kind, source, page, text, quote, scope, claim_id from public.chunks"


def get_chunks(ids: list[int]) -> dict[int, dict] | None:
    rows = _run(lambda c: c.execute(f"{_SEL} where id = any(%s)", (list(ids),)).fetchall())
    return None if rows is None else {r[0]: dict(zip(_COLS, r)) for r in rows}


def claims_on_pages(pages: list[tuple[str, int]]) -> list[int] | None:
    if not pages:
        return []
    srcs, pgs = [p[0] for p in pages], [int(p[1]) for p in pages]
    rows = _run(lambda c: c.execute(
        "select c.id from public.chunks c join unnest(%s::text[], %s::int[]) as w(source, page) "
        "on c.source = w.source and c.page = w.page where c.kind = 'claim' order by c.id", (srcs, pgs)).fetchall())
    return None if rows is None else [r[0] for r in rows]


_WORD = re.compile(r"[A-Za-z0-9]+")


# Okapi BM25 computed in SQL over the generated tsvector column, with SQLite FTS5's formula and
# parameters (k1 = 1.2, b = 0.75, idf = ln((N - n + 0.5) / (n + 0.5)), floored at 1e-6). Postgres' own
# ts_rank has no idf term, which changed most retrieved passages; this keeps the ranking close to the
# tested local version. Small corpus (a few hundred chunks), so the statistics are computed per query.
BM25_SQL = """
with q as (select distinct u.lexeme from unnest(to_tsvector('english', %(text)s)) u),
dl as (select c.id, (select coalesce(sum(coalesce(array_length(u.positions, 1), 1)), 0)
                     from unnest(c.fts) u) as len
       from public.chunks c),
tot as (select count(*)::float as n_docs, greatest(avg(len), 1)::float as avgdl from dl),
d as (select c.id, u.lexeme, coalesce(array_length(u.positions, 1), 1) as tf
      from public.chunks c, unnest(c.fts) u
      where c.fts @@ to_tsquery('english', %(tsq)s) and u.lexeme in (select lexeme from q)),
df as (select lexeme, count(distinct id) as n from d group by lexeme)
select d.id,
       sum(greatest(ln((tot.n_docs - df.n + 0.5) / (df.n + 0.5)), 1e-6)
           * d.tf * 2.2 / (d.tf + 1.2 * (0.25 + 0.75 * dl.len / tot.avgdl))) as score
from d join df using (lexeme) join dl using (id) cross join tot
group by d.id
order by score desc, d.id
limit %(k)s
"""


def keyword_search(query: str, k: int) -> list[tuple[int, float]] | None:
    """BM25 over Postgres full text; the query is an OR of its words (like the local FTS5 query)."""
    words = list(dict.fromkeys(w.lower() for w in _WORD.findall(query) if len(w) > 1))
    if not words:
        return []
    params = {"text": " ".join(words), "tsq": " | ".join(words), "k": k}
    rows = _run(lambda c: c.execute(BM25_SQL, params).fetchall())
    return None if rows is None else [(r[0], float(r[1])) for r in rows]


def _vec_literal(v: np.ndarray) -> str:
    return "[" + ",".join(f"{x:.7g}" for x in np.asarray(v, dtype=np.float32)) + "]"


def dense_search(query_vec: np.ndarray, k: int) -> list[int] | None:
    """pgvector cosine distance (<=>); the same order as the local normalised dot product."""
    lit = _vec_literal(query_vec)
    rows = _run(lambda c: c.execute(
        "select chunk_id from public.vectors order by embedding <=> %s::extensions.vector, chunk_id limit %s",
        (lit, k)).fetchall())
    return None if rows is None else [r[0] for r in rows]


def get_vectors(ids: list[int]) -> dict[int, np.ndarray] | None:
    """Candidate vectors for MMR (L2-normalised, like the local cache)."""
    rows = _run(lambda c: c.execute("select chunk_id, embedding::text from public.vectors where chunk_id = any(%s)",
                                    (list(ids),)).fetchall())
    if rows is None:
        return None
    out = {}
    for cid, txt in rows:
        v = np.array(txt.strip("[]").split(","), dtype=np.float32)
        out[cid] = v / (np.linalg.norm(v) + 1e-9)
    return out


# ------------------------------------------------------------------ runs, cache, feedback
SQL_RUN = ("insert into public.runs (id, created, parent, mode, enquiry, status, json) values (%s,%s,%s,%s,%s,%s,%s::jsonb) "
           "on conflict (id) do update set created=excluded.created, parent=excluded.parent, mode=excluded.mode, "
           "enquiry=excluded.enquiry, status=excluded.status, json=excluded.json")
SQL_CACHE = ("insert into public.llm_cache (key, model, response, usage, created) values (%s,%s,%s,%s,%s) "
             "on conflict (key) do nothing")


def _write(sql: str, params: tuple) -> bool:
    ok = _run(lambda c: c.execute(sql, tuple(_clean(p) for p in params))) is not None
    _state["written" if ok else "pending"] += 1
    return ok


def save_run(row: tuple) -> bool:
    return _write(SQL_RUN, row)


def cache_put(row: tuple) -> bool:
    return _write(SQL_CACHE, row)


def get_run_json(run_id: str) -> Any | None:
    row = _run(lambda c: c.execute("select json from public.runs where id = %s", (run_id,)).fetchone())
    return row[0] if row else None


def list_runs(limit: int) -> list[dict] | None:
    rows = _run(lambda c: c.execute("select id, created, parent, mode, enquiry, status from public.runs "
                                    "order by created desc limit %s", (limit,)).fetchall())
    if rows is None:
        return None
    return [dict(zip(("id", "created", "parent", "mode", "enquiry", "status"), r)) for r in rows]


def cache_get(key: str) -> tuple[str, str | None, str | None, float | None] | None:
    return _run(lambda c: c.execute("select response, usage, model, created from public.llm_cache where key = %s",
                                    (key,)).fetchone())


def add_feedback(run_id: str, created: str, target_: str, verdict: str, comment: str) -> int | None:
    """Insert online first so the id comes from Supabase (unique across machines)."""
    row = _run(lambda c: c.execute(
        "insert into public.feedback (run_id, created, target, verdict, comment) values (%s,%s,%s,%s,%s) returning id",
        tuple(_clean(p) for p in (run_id, created, target_, verdict, comment))).fetchone())
    if row is None:
        _state["pending"] += 1
        return None
    _state["written"] += 1
    return int(row[0])


def list_feedback(run_id: str | None) -> list[dict] | None:
    cols = ("id", "run_id", "created", "target", "verdict", "comment")
    if run_id:
        rows = _run(lambda c: c.execute("select id, run_id, created, target, verdict, comment from public.feedback "
                                        "where run_id = %s order by id", (run_id,)).fetchall())
    else:
        rows = _run(lambda c: c.execute("select id, run_id, created, target, verdict, comment from public.feedback "
                                        "order by id desc limit 200").fetchall())
    return None if rows is None else [dict(zip(cols, r)) for r in rows]


# ------------------------------------------------------------------ sync helpers (store.sync_to_supabase)
def missing_keys(table: str, col: str, keys: list[str]) -> set[str] | None:
    """Keys of local rows that are not online yet (None when offline)."""
    if not keys:
        return set()
    assert (table, col) in (("runs", "id"), ("llm_cache", "key"))
    rows = _run(lambda c: c.execute(f"select {col} from public.{table} where {col} = any(%s)", (list(keys),)).fetchall())
    return None if rows is None else set(keys) - {r[0] for r in rows}


SQL_FEEDBACK_IF_NEW = (
    "insert into public.feedback (run_id, created, target, verdict, comment) select %s, %s, %s, %s, %s "
    "where not exists (select 1 from public.feedback f where f.run_id is not distinct from %s "
    "and f.created is not distinct from %s and f.target is not distinct from %s "
    "and f.verdict is not distinct from %s and f.comment is not distinct from %s)")


def feedback_if_new(rows: list[tuple]) -> int | None:
    """Upload feedback rows (run_id, created, target, verdict, comment) unless identical ones are online."""
    def go(c):
        n = 0
        for r in rows:
            r = tuple(_clean(x) for x in r)
            n += c.execute(SQL_FEEDBACK_IF_NEW, r + r).rowcount or 0
        return n
    return _run(go) if rows else 0


def kb_reason() -> str:
    return _state.get("kb_reason", "")


# ------------------------------------------------------------------ status
def forget_kb_check() -> None:
    """After a local ingest the hosted copy must be checked again."""
    _state["kb"] = None


def status(local_embed_backend: str = "", local_ingested_at: str = "", local_hash: str = "") -> dict:
    """For /api/health and the header chip."""
    if not url():
        return {"mode": "local", "detail": "Local SQLite (SUPABASE_DB_URL not set)"}
    if not enabled():
        return {"mode": "local", "detail": "Local SQLite (DB_BACKEND=sqlite)", "target": target()}
    online()
    kb = kb_ready(local_embed_backend, local_ingested_at, local_hash) if local_embed_backend else bool(_state["kb"])
    if _state["status"] != "online":
        return {"mode": "offline", "target": target(), "kb": "local", "pending": _state["pending"],
                "detail": f"Supabase offline, saving locally ({_state['error']}); sync later with scripts/push_to_supabase.py"}
    return {"mode": "supabase", "target": target(), "kb": "supabase" if kb else "local",
            "written": _state["written"], "pending": _state["pending"],
            "detail": "Supabase: knowledge base, runs, cache and feedback" if kb else
            f"Supabase for runs, cache and feedback; knowledge base local ({_state['kb_reason']})"}


def reset_for_tests() -> None:
    global _conn
    with _lock:
        if _conn is not None:
            try:
                _conn.close()
            except Exception:  # noqa: BLE001
                pass
        _conn = None
        _state.update(status="off", error="", next_try=0.0, ready=False, kb=None, kb_reason="", written=0, pending=0)