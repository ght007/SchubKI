"""Upload the local SQLite store (data/cache/afs.db) to a hosted Postgres (Supabase).

Run from the repo root:
    python scripts/push_to_supabase.py --dry-run              # read + validate only, no network
    python scripts/push_to_supabase.py                        # push, uses SUPABASE_DB_URL from .env
    python scripts/push_to_supabase.py --extra-db ../other/data/cache/afs.db   # also merge runs/cache from another copy
    python scripts/push_to_supabase.py --sql-out supabase_sql # write .sql files for the Supabase SQL editor instead

A real push needs:  pip install "psycopg[binary]"

What ends up in Postgres
- chunks, vectors, meta are REPLACED, so the hosted copy mirrors the latest local ingest.
- runs, llm_cache, feedback are MERGED: rows already online are kept and new ones are added.
  Feedback is matched by content, not id: the app takes feedback ids from Supabase while online and
  from SQLite while offline, so the same id can mean different rows.
- FTS5 is SQLite-only. Postgres gets a generated tsvector column + GIN index on chunks
  instead, and the float32 blobs become a pgvector column. Two SQL functions mirror local
  retrieval: search_chunks(query, n) (full text) and match_chunks(embedding, n) (cosine).
- Row level security is ON with no policies, so the anon/public API key sees nothing. Only
  the database connection string or the service-role key can read the tables.

The app uses Supabase as its main database when SUPABASE_DB_URL is set (backend/app/kb/remote.py):
retrieval runs there once this script has published the knowledge base of the current ingest, and
runs / cache / feedback are written there directly. Run this script after every ingest, and after
working offline (it uploads what was saved locally meanwhile).
"""
from __future__ import annotations

import argparse
import json
import os
import sqlite3
import sys
from array import array
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DB = "data/cache/afs.db"
SQL_FILE_BYTES = 400_000  # keep each generated file small enough for the SQL editor


# ------------------------------------------------------------------ schema
def schema_sql(dim: int) -> str:
    """Idempotent DDL. The vectors table is rebuilt every push because its dimension
    depends on the embedding backend (384 for bge-small, 1024 for the hashing fallback)."""
    return f"""
create schema if not exists extensions;
create extension if not exists vector with schema extensions;

create table if not exists public.chunks (
    id        integer primary key,
    kind      text not null,            -- 'chunk' | 'claim'
    source    text not null,            -- S01..S06
    page      integer not null,
    text      text not null,
    quote     text,
    scope     text,
    claim_id  text,
    fts       tsvector generated always as (to_tsvector('english', text)) stored
);
create index if not exists chunks_fts_idx on public.chunks using gin (fts);
create index if not exists chunks_source_page_idx on public.chunks (source, page);

drop table if exists public.vectors cascade;
create table public.vectors (
    chunk_id  integer primary key references public.chunks (id) on delete cascade,
    embedding extensions.vector({dim}) not null
);

create table if not exists public.meta (
    key   text primary key,
    value text
);

create table if not exists public.runs (
    id       text primary key,
    created  text not null,
    parent   text,
    mode     text,
    enquiry  text,
    status   text,
    json     jsonb not null
);
create index if not exists runs_created_idx on public.runs (created desc);

create table if not exists public.llm_cache (
    key      text primary key,
    model    text,
    response text not null,
    usage    text,
    created  double precision
);

create table if not exists public.feedback (
    id       bigint generated by default as identity primary key,
    run_id   text,
    created  text,
    target   text,
    verdict  text,
    comment  text
);

alter table public.chunks    enable row level security;
alter table public.vectors   enable row level security;
alter table public.meta      enable row level security;
alter table public.runs      enable row level security;
alter table public.llm_cache enable row level security;
alter table public.feedback  enable row level security;

create or replace function public.search_chunks(query text, match_count int default 20)
returns table (id integer, kind text, source text, page integer, text text, rank real)
language sql stable
set search_path = public, extensions
as $$
    select c.id, c.kind, c.source, c.page, c.text,
           ts_rank_cd(c.fts, websearch_to_tsquery('english', query)) as rank
    from public.chunks c
    where c.fts @@ websearch_to_tsquery('english', query)
    order by rank desc
    limit match_count;
$$;

create or replace function public.match_chunks(query_embedding extensions.vector, match_count int default 20)
returns table (id integer, kind text, source text, page integer, text text, similarity double precision)
language sql stable
set search_path = public, extensions
as $$
    select c.id, c.kind, c.source, c.page, c.text,
           1 - (v.embedding <=> query_embedding) as similarity
    from public.vectors v
    join public.chunks c on c.id = v.chunk_id
    order by v.embedding <=> query_embedding
    limit match_count;
$$;
"""


# ------------------------------------------------------------------ read SQLite
def _clean(v):
    """Postgres text cannot hold NUL bytes; SQLite can."""
    return v.replace("\x00", "") if isinstance(v, str) else v


def _rows(con: sqlite3.Connection, sql: str) -> list[dict]:
    return [{k: _clean(r[k]) for k in r.keys()} for r in con.execute(sql)]


def decode_vec(blob: bytes) -> list[float]:
    a = array("f")
    a.frombytes(blob)
    if sys.byteorder != "little":  # numpy wrote little-endian float32
        a.byteswap()
    return a.tolist()


def vec_literal(vec: list[float]) -> str:
    """pgvector text form. %.9g round-trips float32 exactly."""
    return "[" + ",".join(f"{x:.9g}" for x in vec) + "]"


def read_sqlite(path: Path, kb: bool = True) -> dict[str, list]:
    if not path.exists():
        raise SystemExit(f"Database not found: {path}  (run: python -m backend.app.kb.ingest)")
    con = sqlite3.connect(f"file:{path.as_posix()}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row
    data: dict[str, list] = {
        "runs": _rows(con, "SELECT id, created, parent, mode, enquiry, status, json FROM runs ORDER BY created"),
        "llm_cache": _rows(con, "SELECT key, model, response, usage, created FROM llm_cache"),
        "feedback": _rows(con, "SELECT id, run_id, created, target, verdict, comment FROM feedback ORDER BY id"),
    }
    if kb:
        data["chunks"] = _rows(con, "SELECT id, kind, source, page, text, quote, scope, claim_id FROM chunks ORDER BY id")
        data["vectors"] = [{"chunk_id": r[0], "embedding": decode_vec(r[1])}
                           for r in con.execute("SELECT chunk_id, vec FROM vectors ORDER BY chunk_id")]
        data["meta"] = _rows(con, "SELECT key, value FROM meta ORDER BY key")
    con.close()
    for r in data["runs"]:
        json.loads(r["json"])  # fails loudly here rather than half-way through the push
    return data


def merge_extra(data: dict[str, list], extra: dict[str, list]) -> None:
    """Add runs / llm_cache rows from another copy of the DB (first copy wins on key clashes).
    Feedback ids are local autoincrements, so extra feedback rows get new ids."""
    for table, key in (("runs", "id"), ("llm_cache", "key")):
        seen = {r[key] for r in data[table]}
        data[table] += [r for r in extra[table] if r[key] not in seen]
    data["feedback"] += [{**r, "id": None} for r in extra["feedback"]]


def validate(data: dict[str, list]) -> int:
    """Return the embedding dimension; refuse inconsistent data."""
    if not data["chunks"]:
        raise SystemExit("No chunks in the database. Run the ingest first.")
    dims = {len(v["embedding"]) for v in data["vectors"]}
    if len(dims) != 1:
        raise SystemExit(f"Vectors have mixed dimensions {sorted(dims)}. Re-run the ingest.")
    ids = {c["id"] for c in data["chunks"]}
    orphans = [v["chunk_id"] for v in data["vectors"] if v["chunk_id"] not in ids]
    if orphans:
        raise SystemExit(f"{len(orphans)} vectors point to missing chunks (e.g. {orphans[:5]}). Re-run the ingest.")
    return dims.pop()


def summary(data: dict[str, list]) -> str:
    return ", ".join(f"{t}={len(rows)}" for t, rows in data.items())


# ------------------------------------------------------------------ statements
CHUNK_COLS = ("id", "kind", "source", "page", "text", "quote", "scope", "claim_id")
RUN_COLS = ("id", "created", "parent", "mode", "enquiry", "status", "json")
CACHE_COLS = ("key", "model", "response", "usage", "created")
FB_COLS = ("id", "run_id", "created", "target", "verdict", "comment")

RESET_KB = "delete from public.chunks; delete from public.meta;"
FIX_FEEDBACK_SEQ = ("select setval(pg_get_serial_sequence('public.feedback', 'id'), "
                    "coalesce((select max(id) from public.feedback), 0) + 1, false);")


def _insert(table: str, cols: tuple[str, ...], tail: str = "", casts: dict[str, str] | None = None) -> str:
    casts = casts or {}
    vals = ", ".join(f"%s{casts.get(c, '')}" for c in cols)
    return f"insert into public.{table} ({', '.join(cols)}) values ({vals}) {tail}".strip()


INS_CHUNK = _insert("chunks", CHUNK_COLS)
INS_VEC = _insert("vectors", ("chunk_id", "embedding"), casts={"embedding": "::extensions.vector"})
INS_META = _insert("meta", ("key", "value"))
INS_RUN = _insert("runs", RUN_COLS, "on conflict (id) do update set created = excluded.created, parent = excluded.parent, "
                  "mode = excluded.mode, enquiry = excluded.enquiry, status = excluded.status, json = excluded.json",
                  casts={"json": "::jsonb"})
INS_CACHE = _insert("llm_cache", CACHE_COLS, "on conflict (key) do nothing")
# insert a feedback row unless an identical one is already online (ids are not comparable across copies)
INS_FB = ("insert into public.feedback (run_id, created, target, verdict, comment) select %s, %s, %s, %s, %s "
          "where not exists (select 1 from public.feedback f where f.run_id is not distinct from %s "
          "and f.created is not distinct from %s and f.target is not distinct from %s "
          "and f.verdict is not distinct from %s and f.comment is not distinct from %s)")


def _params(data: dict[str, list]):
    """(statement, rows) in dependency order."""
    yield INS_CHUNK, [tuple(r[c] for c in CHUNK_COLS) for r in data["chunks"]]
    yield INS_VEC, [(v["chunk_id"], vec_literal(v["embedding"])) for v in data["vectors"]]
    yield INS_META, [(r["key"], r["value"]) for r in data["meta"]]
    yield INS_RUN, [tuple(r[c] for c in RUN_COLS) for r in data["runs"]]
    yield INS_CACHE, [tuple(r[c] for c in CACHE_COLS) for r in data["llm_cache"]]
    fb = [tuple(r[c] for c in FB_COLS[1:]) for r in data["feedback"]]
    yield INS_FB, [row + row for row in fb]


# ------------------------------------------------------------------ push over a connection
def safe_target(url: str) -> str:
    """Host/db for logging, never the password."""
    p = urlsplit(url)
    return f"{p.hostname}:{p.port or 5432}{p.path}"


def push(data: dict[str, list], url: str, dim: int) -> dict[str, int]:
    try:
        import psycopg
    except ImportError:
        raise SystemExit('psycopg is missing. Install it with:  pip install "psycopg[binary]"')
    # prepare_threshold=None: the Supabase transaction pooler (port 6543) has no prepared statements.
    with psycopg.connect(url, prepare_threshold=None, connect_timeout=20) as conn:
        with conn.transaction():
            conn.execute(schema_sql(dim))
            conn.execute(FIX_FEEDBACK_SEQ)   # rows inserted with explicit ids earlier can leave the counter behind
            conn.execute(RESET_KB)
            with conn.cursor() as cur:
                for stmt, rows in _params(data):
                    if rows:
                        cur.executemany(stmt, rows)
            conn.execute(FIX_FEEDBACK_SEQ)
        counts = {t: conn.execute(f"select count(*) from public.{t}").fetchone()[0]
                  for t in ("chunks", "vectors", "meta", "runs", "llm_cache", "feedback")}
    return counts


# ------------------------------------------------------------------ write .sql files (no network)
def sql_literal(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def _render(stmt: str, row: tuple) -> str:
    parts = stmt.split("%s")
    assert len(parts) == len(row) + 1, stmt
    out = parts[0]
    for val, rest in zip(row, parts[1:]):
        out += sql_literal(val) + rest
    return out + ";"


def write_sql(data: dict[str, list], dim: int, out_dir: Path) -> list[Path]:
    """Numbered files to run in order in the Supabase SQL editor. Each is one transaction."""
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("*.sql"):
        old.unlink()
    files: list[Path] = []

    def emit(name: str, body: str) -> None:
        p = out_dir / f"{len(files):02d}_{name}.sql"
        p.write_text(f"begin;\n{body}\ncommit;\n", encoding="utf-8")
        files.append(p)

    emit("schema", schema_sql(dim).strip() + "\n" + FIX_FEEDBACK_SEQ + "\n" + RESET_KB)
    for stmt, rows in _params(data):
        if not rows:
            continue
        table = stmt.split()[2].split(".")[1]
        buf, size, part = [], 0, 1
        for row in rows:
            line = _render(stmt, row)
            if buf and size + len(line) > SQL_FILE_BYTES:
                emit(f"{table}_{part}", "\n".join(buf))
                buf, size, part = [], 0, part + 1
            buf.append(line)
            size += len(line)
        emit(f"{table}_{part}", "\n".join(buf))
    emit("finish", FIX_FEEDBACK_SEQ)
    return files


# ------------------------------------------------------------------ Supabase pooler fallback
POOLER_REGIONS = ("eu-central-1", "eu-central-2", "eu-west-1", "eu-west-2", "eu-west-3", "eu-north-1",
                  "us-east-1", "us-east-2", "us-west-1", "us-west-2", "ca-central-1", "sa-east-1",
                  "ap-south-1", "ap-southeast-1", "ap-southeast-2", "ap-northeast-1", "ap-northeast-2")


def pooler_candidates(url: str) -> list[str]:
    """Session-pooler URLs for a direct Supabase URL (db.<ref>.supabase.co). The direct host is
    IPv6-only; the pooler speaks IPv4. Region is unknown, so every known region is listed."""
    p = urlsplit(url)
    host = p.hostname or ""
    if not (host.startswith("db.") and host.endswith(".supabase.co")):
        return []
    ref = host[3:-len(".supabase.co")]
    user = p.username or "postgres"
    if "." not in user:
        user = f"{user}.{ref}"
    pw = url.split("://", 1)[1].rsplit("@", 1)[0].split(":", 1)[1] if p.password is not None else ""
    path = p.path or "/postgres"
    return [f"postgresql://{user}:{pw}@{pre}-{region}.pooler.supabase.com:5432{path.lstrip('/') and path}"
            for pre in ("aws-0", "aws-1") for region in POOLER_REGIONS]


def find_pooler(url: str) -> str | None:
    import psycopg
    for cand in pooler_candidates(url):
        try:
            with psycopg.connect(cand, prepare_threshold=None, connect_timeout=8) as c:
                c.execute("select 1")
            return cand
        except Exception as exc:
            msg = str(exc)
            if "password authentication failed" in msg:
                raise SystemExit(f"Found the pooler at {safe_target(cand)} but the password was rejected. "
                                 "Check the password in SUPABASE_DB_URL (write '@' as %40).")
            continue  # wrong region: "Tenant or user not found" / no such host
    return None


# ------------------------------------------------------------------ CLI
def main(argv: list[str] | None = None) -> int:
    try:
        from dotenv import load_dotenv
        load_dotenv(ROOT / ".env")
    except ImportError:
        pass
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", default=os.getenv("DB_PATH", DEFAULT_DB), help="SQLite file (default: DB_PATH or data/cache/afs.db)")
    ap.add_argument("--extra-db", action="append", default=[], help="another afs.db whose runs/llm_cache/feedback are merged in")
    ap.add_argument("--url", default=os.getenv("SUPABASE_DB_URL", ""), help="Postgres URL (default: SUPABASE_DB_URL)")
    ap.add_argument("--dry-run", action="store_true", help="read and validate only")
    ap.add_argument("--sql-out", help="write numbered .sql files to this folder instead of connecting")
    a = ap.parse_args(argv)

    db = Path(a.db) if Path(a.db).is_absolute() else ROOT / a.db
    data = read_sqlite(db)
    for extra in a.extra_db:
        merge_extra(data, read_sqlite(Path(extra), kb=False))
    dim = validate(data)
    print(f"Read {db}: {summary(data)}; embedding dim {dim}")

    if a.dry_run:
        print("Dry run: nothing sent.")
        return 0
    if a.sql_out:
        files = write_sql(data, dim, Path(a.sql_out))
        print(f"Wrote {len(files)} files to {a.sql_out}. Run them in order in the Supabase SQL editor.")
        return 0
    if not a.url:
        raise SystemExit("Set SUPABASE_DB_URL in .env (Supabase: Connect > Session pooler URI) or pass --url.")
    print(f"Pushing to {safe_target(a.url)} ...")
    try:
        counts = push(data, a.url, dim)
    except Exception as exc:  # psycopg.OperationalError, without importing psycopg at module level
        if "resolve host" not in str(exc) or not pooler_candidates(a.url):
            raise
        print("Direct Supabase address is IPv6-only and not reachable here; searching for the IPv4 session pooler ...")
        pooled = find_pooler(a.url)
        if not pooled:
            raise SystemExit("No pooler found. Copy the URI from Supabase > Connect > Method: Session pooler "
                             "into SUPABASE_DB_URL (write '@' in the password as %40).")
        print(f"Found {safe_target(pooled)}. Put this host in SUPABASE_DB_URL to skip the search next time.")
        print(f"Pushing to {safe_target(pooled)} ...")
        counts = push(data, pooled, dim)
    print("Online now: " + ", ".join(f"{t}={n}" for t, n in counts.items()))
    expected = {"chunks": len(data["chunks"]), "vectors": len(data["vectors"]), "meta": len(data["meta"])}
    bad = {t: (counts[t], n) for t, n in expected.items() if counts[t] != n}
    if bad:
        print(f"MISMATCH (online, local): {bad}")
        return 1
    print("OK: knowledge base online matches local.")
    return 0


if __name__ == "__main__":
    sys.exit(main())